// verbs --readme rewrites the README's generated section and keeps its
// begin marker as the README spells it.
func TestVerbsRewritesTheReadmeSection(t *testing.T) {
	tool, _ := testTool(t)
	readme := filepath.Join(t.TempDir(), "README.md")
	marker := "<!-- verbs:begin (generated by rows story verbs --readme README.md; do not edit) -->"
	if err := os.WriteFile(readme, []byte("# rows\n\n"+marker+"\nstale\n<!-- verbs:end -->\ntail\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := tool.Verbs([]string{"--readme", readme}); err != nil {
		t.Fatal(err)
	}
	core, err := testConfig().core("")
	if err != nil {
		t.Fatal(err)
	}
	m, err := coreMinimum(testConfig().Apps, core)
	if err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(readme)
	if want := "# rows\n\n" + marker + "\n\n" + m.Markdown() + "\n<!-- verbs:end -->\ntail\n"; string(data) != want || !strings.Contains(want, "list.move") {
		t.Fatalf("README:\n%s\nwant:\n%s", data, want)
	}
}

func TestTrappedModeIsReported(t *testing.T) {
	m := story.Derive([]story.Step{{Event: story.Event{Key: "i"}, Before: "normal", After: "insert"}})
	if got := m.Trapped(); len(got) != 1 || got[0] != "insert" {
		t.Fatalf("trapped %q", got)
	}
	m = story.Derive([]story.Step{{Before: "normal", After: "insert"}}, []story.Step{{Event: story.Event{Key: "esc"}, Before: "insert", After: "normal"}})
	if got := m.Trapped(); len(got) != 0 {
		t.Fatalf("trapped %q", got)
	}
}

func spillStory(t *testing.T) *story.Story {
	t.Helper()
	core, err := story.LoadDir(filepath.Join("testdata", "stories"))
	if err != nil {
		t.Fatal(err)
	}
	s := story.Find(core, "motions/spill-down")
	if s == nil {
		t.Fatal("no motions/spill-down")
	}
	return s
}

func recording(s *story.Story, at time.Time, keys ...string) *story.Recording {
	rec := &story.Recording{Story: s.Name, Started: at, Initial: s}
	for i, k := range keys {
		rec.Events = append(rec.Events, story.Event{T: int64(100 * (i + 1)), Key: k})
	}
	return rec
}

func TestHistoryRingKeepsFiveNewestFirst(t *testing.T) {
	store := story.Store{Dir: t.TempDir()}
	s := spillStory(t)
	base := time.Unix(1_700_000_000, 0)
	for i := range 7 {
		if _, err := store.Push(recording(s, base.Add(time.Duration(i)*time.Minute), "j")); err != nil {
			t.Fatal(err)
		}
	}
	hist, err := store.History()
	if err != nil {
		t.Fatal(err)
	}
	if len(hist) != story.HistorySize {
		t.Fatalf("%d in the ring", len(hist))
	}
	if !hist[0].Rec.Started.Equal(base.Add(6*time.Minute)) || !hist[4].Rec.Started.Equal(base.Add(2*time.Minute)) {
		t.Fatalf("ring order: newest %v, oldest %v", hist[0].Rec.Started, hist[4].Rec.Started)
	}
}

func TestKeepPromotesOutOfTheRing(t *testing.T) {
	store := story.Store{Dir: t.TempDir()}
	s := spillStory(t)
	for i := range 3 {
		if _, err := store.Push(recording(s, time.Unix(int64(1000+i), 0), "j")); err != nil {
			t.Fatal(err)
		}
	}
	if _, err := store.Keep(2, "mine"); err != nil {
		t.Fatal(err)
	}
	hist, _ := store.History()
	saved, _ := store.Saved()
	if len(hist) != 2 || len(saved) != 1 || saved[0].Name != "mine" || !saved[0].Rec.Started.Equal(time.Unix(1001, 0)) {
		t.Fatalf("after keep: %d in ring, saved %+v", len(hist), saved)
	}
	if _, err := store.Keep(1, "mine"); err == nil {
		t.Fatal("keep over an existing name succeeded")
	}
	if _, err := store.Keep(1, "3"); err == nil {
		t.Fatal("a numeric name was accepted")
	}
	e, err := store.Load("mine")
	if err != nil || e.Rec.Story != s.Name {
		t.Fatalf("load mine: %v %+v", err, e)
	}
}

