func TestTrimWritesAWindowThatRuns(t *testing.T) {
	tool, out := testTool(t)
	store := tool.store()
	s := spillStory(t)
	if _, err := store.Save(recording(s, time.Now(), "j", "j", "j", "j", "j", "j", "j", "k"), "walk"); err != nil {
		t.Fatal(err)
	}
	if err := tool.Trim([]string{"walk", "--at", "4", "--as", "walk window"}); err != nil {
		t.Fatal(err, out.String())
	}
	if err := tool.Trim([]string{"walk", "--from", "3", "--to", "3", "--as", "walk snap", "--snapshot"}); err != nil {
		t.Fatal(err, out.String())
	}
	lib, err := tool.library("")
	if err != nil {
		t.Fatal(err)
	}
	win, snap := story.Find(lib.Stories, "walk window"), story.Find(lib.Stories, "walk snap")
	if win == nil || snap == nil {
		t.Fatalf("trimmed stories not found:\n%s", out.String())
	}
	if win.Base != "recording:walk" || win.Start != 1 || len(win.Script) != 6 {
		t.Fatalf("window: base %q start %d script %v", win.Base, win.Start, win.Script)
	}
	var seed rowsSeed
	if err := json.Unmarshal(snap.Seed, &seed); err != nil || len(seed.Lists) == 0 {
		t.Fatalf("snapshot seed: %v (%s)", err, snap.Seed)
	}
	if snap.Base != "" || len(snap.Script) != 2 || seed.Focus != "b2" {
		t.Fatalf("snapshot: base %q script %v focus %q", snap.Base, snap.Script, seed.Focus)
	}
	for _, st := range []*story.Story{win, snap} {
		if res := lib.Run(st, story.RunOptions{}); !res.OK() {
			t.Fatalf("%s: %v %v", st.Name, res.Err, res.Failed)
		}
	}
	if w, j, err := (story.TrimSpec{From: 2, To: 2, At: -1}).Window(10); err != nil || j-w != 1 {
		t.Fatalf("single-event window widened to %d..%d (%v)", w, j, err)
	}
}

// The TUI records a session, writes it to the ring on q and moves it to
// saved/ under the name typed at the prompt.
func TestTUIRecordsAndSaves(t *testing.T) {
	tool, _ := testTool(t)
	lib, err := tool.library("")
	if err != nil {
		t.Fatal(err)
	}
	h, err := newHost(lib, "rows-story")
	if err != nil {
		t.Fatal(err)
	}
	keytest.Press(h, "enter")
	if h.cur == nil {
		t.Fatal("enter opened no story")
	}
	first := lib.Stories[0].Name
	keytest.Press(h, "j")
	if !strings.Contains(h.View().Content, "rec") {
		t.Fatal("no recording mark in the story box")
	}
	keytest.Press(h, "q")
	if h.cur != nil || h.idx.Runtime.TopModal() == "" {
		t.Fatalf("q did not leave to the save prompt (cur %v, modal %q)", h.cur != nil, h.idx.Runtime.TopModal())
	}
	keytest.Type(h, "first")
	keytest.Press(h, "enter")
	e, err := lib.Store.Load("first")
	if err != nil {
		t.Fatal(err, h.msg)
	}
	if e.Rec.Story != first || len(e.Rec.Events) != 2 || e.Rec.Events[0].Key != "j" || e.Rec.Events[1].Key != "q" {
		t.Fatalf("recording %+v", e.Rec)
	}
	// esc at the prompt keeps the next one in the ring.
	keytest.Press(h, "enter")
	keytest.Press(h, "q")
	keytest.Press(h, "esc")
	if hist, _ := lib.Store.History(); len(hist) != 1 {
		t.Fatalf("%d in the ring after esc", len(hist))
	}
}
